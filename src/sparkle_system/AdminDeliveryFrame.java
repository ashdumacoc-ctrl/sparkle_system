     private void loadDelivery() {

        DefaultTableModel model =
                (DefaultTableModel) jTableDelivery.getModel();

        model.setRowCount(0);

        String sql =
                "SELECT d.delivery_id, "
              + "CONCAT(c.first_name, ' ', c.last_name) AS customer_name, "
+ "od.quantity, "
+ "c.contact, "
+ "c.address, "
              + "u.username, "
              + "d.delivery_status "
              + "FROM deliveries d "
              + "JOIN orders o ON d.order_id = o.order_id "
                + "JOIN order_details od ON o.order_id = od.order_id "
              + "JOIN customers c ON o.customer_id = c.customer_id "
              + "JOIN users u ON d.rider_id = u.user_id "
              + "ORDER BY d.delivery_id DESC";

        try {

            Connection conn = sparklewaterdb_connection.connect();
            PreparedStatement pst = conn.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getInt("delivery_id"),
                    rs.getString("customer_name"),
                    rs.getInt("quantity"),
                    rs.getString("contact"),
                    rs.getString("address"),
                    rs.getString("username"),
                    rs.getString("delivery_status")
                });
            }

            rs.close();
            pst.close();
            conn.close();

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Error loading deliveries: " + e.getMessage());
        }
    }
     
     private void filterDelivery(String status) {

    DefaultTableModel model =
            (DefaultTableModel) jTableDelivery.getModel();

    javax.swing.table.TableRowSorter<DefaultTableModel> sorter =
            new javax.swing.table.TableRowSorter<>(model);

    jTableDelivery.setRowSorter(sorter);

    sorter.setRowFilter(
            javax.swing.RowFilter.regexFilter("^" + status + "$", 6)
    );
}

