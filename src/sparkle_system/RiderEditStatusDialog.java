    private void jButtonUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUpdateActionPerformed
        
        String newStatus =
                jComboBoxEDITSTATUS.getSelectedItem().toString();
if ((currentStatus.equals("Pending") 
        && newStatus.equals("Pending"))
        || (currentStatus.equals("Delivered")
        && !newStatus.equals("Delivered"))) {

    JOptionPane.showMessageDialog(this,
            "Please follow the correct delivery status order.");
    return;
}
      String sql = "UPDATE deliveries SET delivery_status=? WHERE delivery_id=?";

        try {

            Connection conn = sparklewaterdb_connection.connect();

            PreparedStatement pst =
                    conn.prepareStatement(sql);

        pst.setString(1, newStatus);
pst.setInt(2, deliveryID);

            pst.executeUpdate();

            pst.close();
            conn.close();

            JOptionPane.showMessageDialog(this,
                    "Delivery status updated successfully!");

            this.dispose();

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Error updating delivery status: "
                    + e.getMessage());
        }
    }//GEN-LAST:event_jButtonUpdateActionPerformed

