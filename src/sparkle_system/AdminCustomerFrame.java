    private void jCHsearchbuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jCHsearchbuttonActionPerformed
      
        DefaultTableModel model = (DefaultTableModel) jTableCustomerHistory.getModel(); 
        model.setRowCount(0); 

        String search = jSearchCustomertextfield.getText().trim(); 
        
        if (search.matches(".*\\d.*")) { 
            JOptionPane.showMessageDialog(this, "Please enter letters only.", "Invalid Input", JOptionPane.ERROR_MESSAGE);
            return;
        }
       String sql = "SELECT c.customer_id, " 
           + "CONCAT(c.first_name, ' ', c.last_name) AS customer_name, " 
           + "c.contact, c.address, " 
           + "COUNT(o.order_id) AS orders " 
           + "FROM customers c " 
           + "LEFT JOIN orders o ON c.customer_id = o.customer_id " 
           + "WHERE CONCAT(c.first_name, ' ', c.last_name) LIKE ? " 
           + "OR c.address LIKE ? " 
           + "GROUP BY c.customer_id, c.first_name, c.last_name, c.contact, c.address";

        try {
            Connection conn = sparklewaterdb_connection.connect(); 
            PreparedStatement pst = conn.prepareStatement(sql); 

            String keyword = "%" + search + "%"; 

            pst.setString(1, keyword); 
            pst.setString(2, keyword);

            ResultSet rs = pst.executeQuery(); 

            while (rs.next()) { 

                model.addRow(new Object[]{ 
                    rs.getInt("customer_id"),
                    rs.getString("customer_name"),
                    rs.getString("contact"),
                    rs.getString("address"),
                    rs.getInt("orders")
                });
            }

            rs.close(); 
            pst.close();
            conn.close();

        } catch (SQLException e) { 
            JOptionPane.showMessageDialog(this,
                    "Error searching customers: " + e.getMessage()); 
        }
    }//GEN-LAST:event_jCHsearchbuttonActionPerformed
    private void jCHViewCustomerButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jCHViewCustomerButtonActionPerformed
      
        int selectedRow = jTableCustomerHistory.getSelectedRow(); 

        if (selectedRow == -1) { 
            JOptionPane.showMessageDialog(this,
                    "Please select a customer first.");
            return; 
        }

        String customerID = jTableCustomerHistory.getValueAt(selectedRow, 0).toString(); 
        String customerName = jTableCustomerHistory.getValueAt(selectedRow, 1).toString();
        String contact = jTableCustomerHistory.getValueAt(selectedRow, 2).toString();
        String address = jTableCustomerHistory.getValueAt(selectedRow, 3).toString();
        String orders = jTableCustomerHistory.getValueAt(selectedRow, 4).toString();

        AdminCustomerDetailsDialog details = new AdminCustomerDetailsDialog(this, true, customerID, customerName, contact, address, orders);

        details.setLocationRelativeTo(this); 
        details.setVisible(true); 
    }//GEN-LAST:event_jCHViewCustomerButtonActionPerformed

