  private void loadReport() {

    LocalDate today = LocalDate.now();

    jLabelReportDate.setText(today.toString());

    jLabelDate.setText(
        today.format(DateTimeFormatter.ofPattern("MMMM d, yyyy"))
    );

    String sql = """
        SELECT
        COALESCE(SUM(CASE WHEN payment_type = 'Cash'
        THEN total_amount ELSE 0 END), 0) AS cash,

        COALESCE(SUM(CASE WHEN payment_type = 'GCash'
        THEN total_amount ELSE 0 END), 0) AS gcash,

        COALESCE(SUM(total_amount), 0) AS total,

        COUNT(*) AS orders

        FROM orders
        WHERE order_date >= ?
        AND order_date < ?
        """;

    try (Connection con = sparklewaterdb_connection.connect();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, today.toString());
        pst.setString(2, today.plusDays(1).toString());

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            jLabelCash.setText("₱" +
                String.format("%,.2f", rs.getDouble("cash")));

            jLabelGcash.setText("₱" +
                String.format("%,.2f", rs.getDouble("gcash")));

            jLabelTotalSales.setText("₱" +
                String.format("%,.2f", rs.getDouble("total")));

            jLabelTotalOrders.setText(
                String.valueOf(rs.getInt("orders"))
            );
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Error loading report: " + e.getMessage());
    }
} 
