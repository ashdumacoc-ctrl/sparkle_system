    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
        String user = username.getText();
        String pass = new String(password.getPassword());

        String sql = "SELECT u.user_id, u.username, r.role_name "
        + "FROM users u "
        + "JOIN roles r ON u.role_id = r.role_id "
        + "WHERE u.username = ? AND u.password = ?";

        if (user.isEmpty() ||  pass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter username and password", "error" , JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {

            Connection conn = sparklewaterdb_connection.connect();

            PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, user);
            pst.setString(2, pass);

            ResultSet rs = pst.executeQuery();

            if (rs.next()) {

                int userId = rs.getInt("user_id");
                String loggedUser = rs.getString("username");
                String role = rs.getString("role_name");

                
                usersession.setUser(userId, loggedUser);

                if (role.equals("Admin")) {

                    usersession.setUser(userId, user);
                    JOptionPane.showMessageDialog(this, "Login Successful!");
                    new AdminDashboardFrame().setVisible(true);

                } else if (role.equals("Rider")) {

                    usersession.setUser(userId, user);
                    JOptionPane.showMessageDialog(this, "Login Successful!");
                    new RiderDashboardFrame().setVisible(true);
                }

                this.dispose();

            } else {

                JOptionPane.showMessageDialog(this,"Invalid username or password.", "error" , JOptionPane.ERROR_MESSAGE);
            }

            rs.close();
            pst.close();
            conn.close();

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,"Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_loginActionPerformed

