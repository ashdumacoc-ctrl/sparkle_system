private void loadDeliverySummary() {

    String sql = "SELECT "
            + "COUNT(*) AS assigned, "
            + "COALESCE(SUM(CASE WHEN delivery_status = 'Delivered' THEN 1 ELSE 0 END), 0) AS completed, "
            + "COALESCE(SUM(CASE WHEN delivery_status = 'Pending' THEN 1 ELSE 0 END), 0) AS pending "
            + "FROM deliveries WHERE rider_id = ?";

    try {
        Connection conn = sparklewaterdb_connection.connect();
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setInt(1, 2);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            jLabelRD1.setText(rs.getString("assigned"));
            jLabelRD2.setText(rs.getString("completed"));
            jLabelRD3.setText(rs.getString("pending"));
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error loading delivery summary: " + e.getMessage());
    }
}
    private void loadTodayDelivery() {
     DefaultTableModel model =
            (DefaultTableModel) jTableTodayDelivery.getModel();

    model.setRowCount(0);

    String sql =
            "SELECT o.order_id, "
          + "CONCAT(c.first_name, ' ', c.last_name) AS customer_name, "
+ "od.quantity, "
+ "o.total_amount, "
          + "d.delivery_status "
          + "FROM deliveries d "
          + "JOIN orders o ON d.order_id = o.order_id "
            + "JOIN order_details od ON o.order_id = od.order_id "
          + "JOIN customers c ON o.customer_id = c.customer_id "
          + "WHERE d.rider_id = ? "
          + "AND DATE(o.order_date) = CURDATE() "
          + "ORDER BY o.order_id DESC";

    try {

        Connection conn = sparklewaterdb_connection.connect();

        PreparedStatement pst =
                conn.prepareStatement(sql);

        pst.setInt(1, 2);

        ResultSet rs = pst.executeQuery();

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("order_id"),
                rs.getString("customer_name"),
                rs.getInt("quantity"),
                rs.getDouble("total_amount"),
                rs.getString("delivery_status")
            });
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error loading today's deliveries: "
                + e.getMessage());
    }
}

