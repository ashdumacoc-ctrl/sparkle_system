    private void jButtonSaveEOActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSaveEOActionPerformed


    int orderID = Integer.parseInt(jEOOrderID.getText());
    String customer = jEOCustomer.getText().trim();
    String contact = jEOContact.getText().trim();
    String payment = jEOPayment.getSelectedItem().toString();

    if (customer.isEmpty() || contact.isEmpty()
            || jEOQuantity.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please complete all fields.");
        return;
    }

    try {

        int quantity = Integer.parseInt(jEOQuantity.getText().trim());

        if (quantity <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Quantity must be at least 1.");
            return;
        }

        double subtotal = quantity * 25.00;
double deliveryFee = 0;

if ("Delivery".equals(orderType) && quantity < 5) {
    deliveryFee = quantity * 5;
}

double total = subtotal + deliveryFee;

        Connection conn = sparklewaterdb_connection.connect();


        // UPDATE ORDER
        String sqlOrder =
                "UPDATE orders SET payment_type=?, total_amount=? "
              + "WHERE order_id=?";

        PreparedStatement pst2 = conn.prepareStatement(sqlOrder);

        pst2.setString(1, payment);
        pst2.setDouble(2, total);
        pst2.setInt(3, orderID);

        pst2.executeUpdate();


        // UPDATE QUANTITY
        String sqlDetails =
                "UPDATE order_details SET quantity=?, subtotal=? "
              + "WHERE order_id=?";

        PreparedStatement pst3 = conn.prepareStatement(sqlDetails);

        pst3.setInt(1, quantity);
        pst3.setDouble(2, subtotal);
        pst3.setInt(3, orderID);

        pst3.executeUpdate();


        jEOTotal.setText("₱" + total);

        pst2.close();
        pst3.close();
        conn.close();

        JOptionPane.showMessageDialog(this,
                "Order updated successfully!");

        this.dispose();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Quantity must be a number.");

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error updating order: " + e.getMessage());
    }

    }//GEN-LAST:event_jButtonSaveEOActionPerformed

