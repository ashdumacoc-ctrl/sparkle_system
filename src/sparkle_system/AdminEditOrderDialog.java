   public AdminEditOrderDialog(java.awt.Frame parent, boolean modal,
        String orderID, String customer, String contact,
        String date, String payment, String orderType, String total) {

    super(parent, modal);
    initComponents();

    jEOOrderID.setText(orderID);
    jEOCustomer.setText(customer);
    jEOContact.setText(contact);
    jEOOrderDate.setText(date);
    jEOTotal.setText("₱" + total);
    jEOCustomer.setEditable(false);

    jEOOrderID.setEditable(false);
    jEOOrderDate.setEditable(false);
    jEOTotal.setEditable(false);
    jEOCustomer.setEditable(false);
    jEOContact.setEditable(false);
    
    try {
    Connection conn = sparklewaterdb_connection.connect();

    String sql = "SELECT od.quantity, o.order_type "
           + "FROM order_details od "
           + "JOIN orders o ON od.order_id = o.order_id "
           + "WHERE od.order_id=?";

    PreparedStatement pst = conn.prepareStatement(sql);
    pst.setInt(1, Integer.parseInt(orderID));

    ResultSet rs = pst.executeQuery();

   if (rs.next()) {
    jEOQuantity.setText(rs.getString("quantity"));
    this.orderType = rs.getString("order_type");
    jEOOrderType.setText(this.orderType);

    jEOPayment.removeAllItems();

    if ("Walk-in".equals(orderType)) {
        jEOPayment.addItem("Cash");
    } else if ("Delivery".equals(orderType)) {
        jEOPayment.addItem("Cash on Delivery");
        jEOPayment.addItem("GCash");
    }

    jEOPayment.setSelectedItem(payment);
}

    rs.close();
    pst.close();
    conn.close();

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
}

