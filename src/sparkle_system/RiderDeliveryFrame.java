    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
             int selectedRow = jTableRiderDelivery.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(this,
            "Please select a delivery first.");
    return;
}

int deliveryID = Integer.parseInt(
        jTableRiderDelivery.getValueAt(selectedRow, 0).toString()
);

String sql =
        "SELECT CONCAT(c.first_name, ' ', c.last_name) AS customer_name, "
      + "c.contact, "
      + "c.address, "
      + "o.order_id, "
      + "o.payment_type, "
      + "u.username, "
      + "d.delivery_status "
      + "FROM deliveries d "
      + "JOIN orders o ON d.order_id = o.order_id "
      + "JOIN customers c ON o.customer_id = c.customer_id "
      + "JOIN users u ON d.rider_id = u.user_id "
      + "WHERE d.delivery_id = ?";

try {

    Connection conn = sparklewaterdb_connection.connect();

    PreparedStatement pst = conn.prepareStatement(sql);

    pst.setInt(1, deliveryID);

    ResultSet rs = pst.executeQuery();
    if (rs.next()) {

    String customer = rs.getString("customer_name");
    String contact = rs.getString("contact");
    String address = rs.getString("address");
    String order = rs.getString("order_id");
    String payment = rs.getString("payment_type");
    String rider = rs.getString("username");
    String status = rs.getString("delivery_status");
    
    RiderDeliveryDetailsDialog dialog = new RiderDeliveryDetailsDialog(
            this,
            true,
            customer,
            contact,
            address,
            order,
            payment,
            rider,
            status
    );

    dialog.setLocationRelativeTo(this);
    dialog.setVisible(true);
}
    rs.close();
pst.close();
conn.close();
} catch (SQLException e) {

    JOptionPane.showMessageDialog(this,
            "Error loading delivery details: " + e.getMessage());
}
    }//GEN-LAST:event_jButton2ActionPerformed

